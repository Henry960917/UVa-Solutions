#include <iostream>
#include <queue>
#include <vector>
#include <map>
using namespace std;

int main(){
    int t;
    while(cin >> t && t!=0){
        map<int, int> team;
        for(int i = 0; i<t; i++){
            int n, xi;
            cin >> n;
            for(int j = 0; j<n; j++){
                cin >> xi;
                team[xi]=i;
            }
        }
        string cmd;
        while(cin >> cmd){
            int x;
            if(cmd=="STOP"){
                break;
            }
            cin >> x;
            
        }
    }
    return 0;
}

